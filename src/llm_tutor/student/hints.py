"""Лестница подсказок: уровни и границы шага (Срез 5.4).

Уровень выбирает тьютор — модель судит по диалогу, застрял ли ученик. Но
границы держит код: не ниже нуля, не выше максимума и **не больше +1 за ход**.
Без последнего ограничения один неудачный ответ модели выдал бы готовый
разбор вместо подсказки, а политика «не выдавать решение» держится как раз
на постепенности.
"""

MAX_HINT_LEVEL = 4

# Название уровня — для промпта и отладки.
HINT_LEVEL_NAMES: dict[int, str] = {
    0: "без подсказки — только сократовские вопросы",
    1: "намёк",
    2: "наводящий вопрос",
    3: "частичное решение",
    4: "разбор",
}


def next_hint_level(current: int, suggested: int) -> int:
    """Уровень подсказки на следующий ход.

    Снижать можно свободно (ученик пошёл сам), поднимать — не более чем на
    шаг от текущего.
    """
    clamped = min(MAX_HINT_LEVEL, max(0, suggested))
    return clamped if clamped <= current else current + 1
